#!/usr/bin/env python3
"""Apply the three patches needed to build PYNQ's base overlay with Vivado 2026.1.

The base overlay tcl is generated by Vivado 2024.1 and is not a hand-written
script, so patching it is the only practical route. Every patch is checked: if
the original text is missing, the script fails loudly instead of silently
producing a build that differs from what we think we built.

Patch 1  version guard        2024.1 -> 2026.1
Patch 2  ip_repo_paths         ../../ip -> the extracted PYNQ ip directory
Patch 3  PFM_NAME              ${overlay_name} -> base
         (2026.1 validates this string; 2024.1 did not, and the generated tcl
          never substituted the variable because it sits inside braces)
"""

from __future__ import annotations

import argparse
import sys

PATCHES = [
    (
        "version guard",
        "set scripts_vivado_version 2024.1",
        "set scripts_vivado_version 2026.1",
    ),
    (
        "PFM_NAME literal",
        "PFM_NAME {xilinx.com:xd:${overlay_name}:1.0}",
        "PFM_NAME {xilinx.com:xd:base:1.0}",
    ),
]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("base_tcl")
    ap.add_argument("ip_dir", help="absolute path to the extracted PYNQ boards/ip")
    args = ap.parse_args(argv)

    with open(args.base_tcl, "r", encoding="utf-8") as fh:
        text = fh.read()

    for name, old, new in PATCHES:
        if old not in text:
            print(f"FAIL: patch '{name}' target not found in {args.base_tcl}")
            print(f"      expected: {old}")
            return 1
        text = text.replace(old, new)
        print(f"patched: {name}")

    # ip_repo_paths: the original is relative to the PYNQ repo layout
    # (boards/Pynq-Z2/base/../../ip). Use an absolute path so the build works
    # wherever the sources were extracted.
    old_ip = "set_property  ip_repo_paths  ../../ip [current_project]"
    new_ip = ('set_property  ip_repo_paths [file normalize {%s}] [current_project]'
              % args.ip_dir)
    if old_ip not in text:
        # tolerate the two-space variant used by some generator versions
        old_ip2 = "set_property ip_repo_paths ../../ip [current_project]"
        if old_ip2 not in text:
            print("FAIL: patch 'ip_repo_paths' target not found")
            return 1
        text = text.replace(old_ip2, new_ip)
    else:
        text = text.replace(old_ip, new_ip)
    print("patched: ip_repo_paths")

    with open(args.base_tcl, "w", encoding="utf-8") as fh:
        fh.write(text)

    print("RESULT: PATCH OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
